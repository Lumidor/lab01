pr1 = input('Введите название предмета:')
pr2 = input('Введите название еще одного предмета:')
za1 = int(input(f'Введите кол-во занятий в неделю по {pr1}:'))
za2 = int(input(f'Введите кол-во занятий в неделю по {pr2}:'))
mi1 = int(input(f'Введите продолжительность занятия в минутах по {pr1}:'))
mi2 = int(input(f'Введите продолжительность занятия в минутах по {pr2}:'))
sv = float(input('Введите свободное время на неделю в часах:'))
if za1>0 and za2>0 and mi1>0 and mi2>0 and sv>=(((mi1*za1)+(mi2*za2))/60):
    print(f'{pr1}: Одно занятие:{mi1} мин, Общая нагрузка:{mi1*za1} мин, Общая нагрузка в часах:{(mi1*za1/60):.2f}')
    print(f'{pr2}: Одно занятие:{mi2} мин, Общая нагрузка:{mi2*za2} мин, Общая нагрузка в часах:{(mi2*za2/60):.2f}')
    print(f'Общая нагрузка за неделю: {mi1*za1+mi2*za2} мин, в часах: {((mi1*za1+mi2*za2)/60):.2f}')
    print(f'Остаток времени: {(sv-((mi1*za1+mi2*za2)/60)):.2f} часов')
    print(f'Нагрузка за 4 одинаковые недели: {(mi1*za1+mi2*za2)*4} мин, в часах: {(((mi1*za1+mi2*za2)*4)/60):.2f}')
else:
    print('Вы ввели отрицательное число или время отдыха меньше нагрузки, перезапустите программу и введите правильно')
